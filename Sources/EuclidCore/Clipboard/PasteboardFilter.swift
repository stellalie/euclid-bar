/// Decides whether a pasteboard change should be recorded, based on its type
/// identifiers. See http://nspasteboard.org for the marker conventions that
/// password managers and well-behaved apps use.
public enum PasteboardFilter {
    /// Written by Euclid itself when pasting, so we don't re-record our own writes.
    public static let euclidMarker = "dev.euclid.own"

    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",   // passwords (1Password, Bitwarden, Keychain…)
        "org.nspasteboard.TransientType",   // temporary, not meant for history
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        euclidMarker,
    ]

    public static func shouldRecord(types: [String]) -> Bool {
        !types.contains(where: ignoredTypes.contains)
    }
}
